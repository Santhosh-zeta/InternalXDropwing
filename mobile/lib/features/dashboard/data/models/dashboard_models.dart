import 'package:freezed_annotation/freezed_annotation.dart';

part 'dashboard_models.freezed.dart';
part 'dashboard_models.g.dart';

@freezed
class AnalyticsResponse with _$AnalyticsResponse {
  const factory AnalyticsResponse({
    @Default([]) List<ActivityItem> recentActivity,
    @Default([]) List<Announcement> announcements,
    // Add other fields as necessary if they are ever needed (budget, etc)
    // but the prompt says NO charts, NO budget. So we only need what's rendered.
  }) = _AnalyticsResponse;

  factory AnalyticsResponse.fromJson(Map<String, dynamic> json) => _$AnalyticsResponseFromJson(json);
}

@freezed
class ActivityItem with _$ActivityItem {
  const factory ActivityItem({
    required String action,
    @JsonKey(name: 'created_at') required String createdAt,
    @JsonKey(name: 'user_name') String? userName,
  }) = _ActivityItem;

  factory ActivityItem.fromJson(Map<String, dynamic> json) => _$ActivityItemFromJson(json);
}

@freezed
class Announcement with _$Announcement {
  const factory Announcement({
    required int id,
    required String type,
    required String title,
    required String content,
  }) = _Announcement;

  factory Announcement.fromJson(Map<String, dynamic> json) => _$AnnouncementFromJson(json);
}

@freezed
class DashboardTask with _$DashboardTask {
  const factory DashboardTask({
    required int id,
    required String title,
    required String status,
    required String priority,
    @JsonKey(name: 'assigned_to') int? assignedTo,
    @JsonKey(name: 'due_date') String? dueDate,
  }) = _DashboardTask;

  factory DashboardTask.fromJson(Map<String, dynamic> json) => _$DashboardTaskFromJson(json);
}

@freezed
class NotificationItem with _$NotificationItem {
  const factory NotificationItem({
    required int id,
    @JsonKey(name: 'is_read') required int isRead, // SQLite bools are often returned as 0/1, or we can use dynamic
  }) = _NotificationItem;

  factory NotificationItem.fromJson(Map<String, dynamic> json) => _$NotificationItemFromJson(json);
}

// A simple UI model for KPI cards, not generated by Freezed to avoid JSON logic unless needed
class KPICard {
  final String title;
  final String value;
  final String icon;
  final String color;

  KPICard({
    required this.title,
    required this.value,
    required this.icon,
    required this.color,
  });
}
